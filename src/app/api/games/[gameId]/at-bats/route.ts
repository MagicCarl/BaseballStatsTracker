import { NextRequest, NextResponse } from "next/server";
import { Prisma } from "@prisma/client";
import { getAuthUser, unauthorized } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { ALL_RESULTS, PITCH_RESULTS } from "@/lib/constants";
import {
  BATTER,
  RunnerMoves,
  checkMoves,
  defaultRbi,
  normalizeRuns,
  replayPlays,
  runsInMoves,
  weAreBatting,
} from "@/lib/game-state";
import { loadPlays, lockGame, nextSequence, syncGameState } from "@/lib/game-sync";
import { z } from "zod/v4";

const runnerMovesSchema = z.record(
  z.string().max(64),
  z.union([z.literal(1), z.literal(2), z.literal(3), z.literal("home"), z.literal("out")])
);

const createAtBatSchema = z
  .object({
    // Generated by the screen, so a retry after a lost response can't save the play twice.
    id: z.string().min(8).max(64).optional(),
    playerId: z.string().nullish(),
    opponentBatterId: z.string().nullish(),
    opponentPitcherId: z.string().nullish(),
    result: z.enum(ALL_RESULTS),
    runnerMoves: runnerMovesSchema.optional(),
    lineupSpot: z.number().int().min(1).max(100).nullish(),
    rbi: z.number().int().min(0).max(4).optional(),
    // Only sent by screens still open from before runners were tracked.
    runsScored: z.number().int().min(0).max(4).optional(),
    runnerScored: z.boolean().optional(),
    stolenBases: z.number().int().min(0).max(3).optional(),
    caughtStealing: z.number().int().min(0).max(3).optional(),
    hitLocationX: z.number().nullish(),
    hitLocationY: z.number().nullish(),
    notes: z.string().max(1000).nullish(),
    pitches: z
      .array(
        z.object({
          result: z.enum(PITCH_RESULTS),
          locationX: z.number().nullish(),
          locationY: z.number().nullish(),
        })
      )
      .max(100)
      .optional(),
  })
  .refine((b) => !b.playerId !== !b.opponentBatterId, {
    message: "An at-bat needs exactly one batter",
  });

class PlayRejected extends Error {
  constructor(message: string, public status: number) {
    super(message);
  }
}

export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ gameId: string }> }
) {
  const user = await getAuthUser(req);
  if (!user) return unauthorized();

  const { gameId } = await params;

  const atBats = await prisma.atBat.findMany({
    where: { gameId, game: { team: { organization: { ownerId: user.id } } } },
    include: { player: true, opponentBatter: true, opponentPitcher: true, pitches: { orderBy: { pitchNumber: "asc" } } },
    orderBy: { atBatNumberInGame: "asc" },
  });

  return NextResponse.json(atBats);
}

export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ gameId: string }> }
) {
  const user = await getAuthUser(req);
  if (!user) return unauthorized();

  const { gameId } = await params;
  const parsed = createAtBatSchema.safeParse(await req.json());
  if (!parsed.success) {
    return NextResponse.json({ error: parsed.error.issues[0].message }, { status: 400 });
  }
  const body = parsed.data;

  const owned = await prisma.game.findFirst({
    where: { id: gameId, team: { organization: { ownerId: user.id } } },
  });
  if (!owned) {
    return NextResponse.json({ error: "Game not found" }, { status: 404 });
  }

  // A retry of a play that already saved is a success, not a second play.
  if (body.id) {
    const saved = await prisma.atBat.findFirst({
      where: { id: body.id, gameId },
      include: { player: true, opponentBatter: true, opponentPitcher: true },
    });
    if (saved) return NextResponse.json(saved, { status: 200 });
  }

  // Batters and pitchers must belong to this game's team.
  const [player, opponentBatter, opponentPitcher] = await Promise.all([
    body.playerId ? prisma.player.findFirst({ where: { id: body.playerId, teamId: owned.teamId } }) : null,
    body.opponentBatterId ? prisma.opponentBatter.findFirst({ where: { id: body.opponentBatterId, gameId } }) : null,
    body.opponentPitcherId ? prisma.opponentPitcher.findFirst({ where: { id: body.opponentPitcherId, gameId } }) : null,
  ]);
  if ((body.playerId && !player) || (body.opponentBatterId && !opponentBatter) || (body.opponentPitcherId && !opponentPitcher)) {
    return NextResponse.json({ error: "Batter or pitcher not found in this game" }, { status: 400 });
  }

  try {
    // All or nothing, so a dropped connection can't leave half an at-bat to re-enter.
    const atBat = await prisma.$transaction(async (tx) => {
      const game = await lockGame(tx, gameId);
      if (game.status === "final") throw new PlayRejected("This game has ended", 409);

      const { plays } = await loadPlays(tx, gameId);
      const moves = body.runnerMoves as RunnerMoves | undefined;

      if (moves) {
        if (!!body.playerId !== weAreBatting(game.isHome, game.isTopOfInning)) {
          throw new PlayRejected("That team isn't batting right now", 409);
        }
        if (moves[BATTER] === undefined) throw new PlayRejected("Where did the batter end up?", 400);
        if (checkMoves(moves, replayPlays(plays).bases, true)) {
          throw new PlayRejected("Those runner moves don't match who's on base", 400);
        }
        if (body.result === "home_run" && moves[BATTER] !== "home") {
          throw new PlayRejected("A home run has to score the batter", 400);
        }
      }

      const runs = moves
        ? {
            // An RBI is a run that scored, so it can't be more than the runs on the play.
            rbi: Math.min(body.rbi ?? defaultRbi(body.result, moves), runsInMoves(moves)),
            runsScored: runsInMoves(moves),
            runnerScored: moves[BATTER] === "home",
          }
        : normalizeRuns({ ...body, result: body.result });

      const created = await tx.atBat.create({
        data: {
          ...(body.id ? { id: body.id } : {}),
          gameId,
          playerId: body.playerId || null,
          opponentBatterId: body.opponentBatterId || null,
          opponentPitcherId: body.opponentPitcherId || null,
          inning: game.currentInning,
          isTop: game.isTopOfInning,
          atBatNumberInGame: nextSequence(plays),
          result: body.result,
          ...runs,
          runnerMoves: moves ?? Prisma.JsonNull,
          lineupSpot: body.lineupSpot ?? null,
          stolenBases: body.stolenBases || 0,
          caughtStealing: body.caughtStealing || 0,
          hitLocationX: body.hitLocationX ?? null,
          hitLocationY: body.hitLocationY ?? null,
          notes: body.notes || null,
          pitchCount: body.pitches?.length || null,
          pitches: body.pitches?.length
            ? {
                create: body.pitches.map((pitch, i) => ({
                  pitchNumber: i + 1,
                  result: pitch.result,
                  locationX: pitch.locationX ?? null,
                  locationY: pitch.locationY ?? null,
                })),
              }
            : undefined,
        },
        include: { player: true, opponentBatter: true, opponentPitcher: true },
      });

      await syncGameState(tx, gameId);
      await tx.game.update({ where: { id: gameId }, data: { status: "in_progress" } });
      return created;
    });

    return NextResponse.json(atBat, { status: 201 });
  } catch (e) {
    if (e instanceof PlayRejected) {
      return NextResponse.json({ error: e.message }, { status: e.status });
    }
    throw e;
  }
}
